import assert from 'node:assert/strict';

globalThis.location = { hostname: 'localhost' };
globalThis.fetch = async () => ({ ok: true, json: async () => ({ tracks: [] }) });
const buzzes = [];
Object.defineProperty(globalThis, 'navigator', { configurable: true, value: { language: 'de-DE', vibrate: value => { buzzes.push(value); return true; } } });
globalThis.document = { hidden: false };
const { AudioManager } = await import('../js/audio.js');
const { playGameImpact } = await import('../js/helpers/gameFeedback.js');
const { cancelHaptics } = await import('../js/helpers/haptics.js');
const { CONFIG } = await import('../js/config.js');
const audio = new AudioManager();
let voices = [];
audio._play = (...args) => voices.push(args);
audio._scheduleSfx = () => { throw new Error('Answer impacts must never schedule later notes'); };
const save = { getSetting: () => true };
const game = { mode: 'klassik', feverActive: false };
const result = { correct: true, direction: 'ul', reaction: CONFIG.PERFECT_WINDOW_MS + 1, streak: 1 };
const reset = () => { voices = []; buzzes.length = 0; };

playGameImpact(result, game, audio, save);
assert.equal(voices.length, 2);
assert.deepEqual(buzzes, [[8]]);
assert.ok(voices.every(v => v[5] === -.28 && v[2] <= .1 && v[3] <= .1 && v[6] >= .003));
reset();
playGameImpact({ ...result, reaction: 100 }, game, audio, save);
assert.equal(voices.length, 3);
assert.deepEqual(buzzes, [[12]], 'Perfect answers must have one short, not stacked, vibration');
reset();
playGameImpact({ ...result, bonus: 'golden', direction: 'dr' }, game, audio, save);
assert.equal(voices.length, 3);
assert.deepEqual(buzzes, [[10, 8, 12]]);
assert.ok(voices.every(v => v[5] === .28));
const notes = [];
for (const mode of ['klassik', 'mathe', 'memo', 'stroop']) {
  reset(); playGameImpact(result, { ...game, mode }, audio, save); notes.push(voices[0][0]);
}
assert.equal(new Set(notes).size, 4, 'World families must have their own contact timbre/register');
const registers = ['klassik', 'beginner', 'expert', 'mathe', 'wissen', 'memo', 'sequenz', 'stroop', 'fokus', 'chaos'].map(mode => {
  reset(); playGameImpact(result, { ...game, mode }, audio, save); return voices[0][0];
});
assert.equal(new Set(registers).size, 10, 'Each live mode has a distinct, restrained contact register');
reset();
playGameImpact({ ...result, correct: false, direction: 'ur' }, game, audio, save);
assert.equal(voices.length, 2);
assert.ok(voices.every(v => v[5] === 0), 'Wrong answers must not pan toward a solution');
assert.deepEqual(buzzes, [[12, 16, 12]]);
reset();
playGameImpact({ ...result, correct: false, autoMiss: true }, game, audio, save);
assert.equal(voices.length, 1);
assert.equal(buzzes.length, 0, 'Idle timeouts must not produce repeated vibration');
reset();
audio.enabled = false;
playGameImpact(result, game, audio, save);
assert.equal(voices.length, 0);
assert.equal(buzzes.length, 1, 'Sound and haptics retain independent controls');
audio.enabled = true;
reset();
playGameImpact(result, game, audio, { getSetting: () => false });
assert.equal(voices.length, 2);
assert.equal(buzzes.length, 0);
reset();
audio._pageHidden = document.hidden = true;
playGameImpact(result, game, audio, save);
assert.equal(voices.length + buzzes.length, 0, 'Hidden gameplay must stay silent and still');
audio._pageHidden = document.hidden = false;
cancelHaptics();
assert.deepEqual(buzzes, [0]);
navigator.vibrate = () => { throw new Error('Vibration is blocked'); };
assert.doesNotThrow(() => playGameImpact(result, game, audio, save));
reset();
audio.cornerShuffleWarn(); audio.cornerShuffleDone();
assert.equal(voices.length, 2);
assert.ok(voices.every(v => v[2] <= .05), 'Shuffle cues must not queue long chords over the next answer');
console.log('Game feedback tests passed: world timbres, bounded immediate voices, single short haptic, independent settings, hidden/blocked-device safety.');
